type Poly = { pts: number[]; minX: number; maxX: number; minY: number; maxY: number }
const prep = (rings: number[][]): Poly[] =>
  rings.map((pts) => {
    let minX = 999, maxX = -999, minY = 999, maxY = -999
    for (let i = 0; i < pts.length; i += 2) {
      minX = Math.min(minX, pts[i]); maxX = Math.max(maxX, pts[i])
      minY = Math.min(minY, pts[i + 1]); maxY = Math.max(maxY, pts[i + 1])
    }
    return { pts, minX, maxX, minY, maxY }
  })

function inside(p: Poly, x: number, y: number) {
  if (x < p.minX || x > p.maxX || y < p.minY || y > p.maxY) return false
  const v = p.pts
  let c = false
  for (let i = 0, j = v.length - 2; i < v.length; j = i, i += 2) {
    const xi = v[i], yi = v[i + 1], xj = v[j], yj = v[j + 1]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}

let landP: Poly[] | null = null
let waterP: Poly[] | null = null

export function isLand(lon: number, lat: number) {
  if (lat < -70) return true // Antarctica
  landP ??= prep(LAND)
  waterP ??= prep(WATER)
  for (const w of waterP) if (inside(w, lon, lat)) return false
  for (const l of landP) if (inside(l, lon, lat)) return true
  return false
}

